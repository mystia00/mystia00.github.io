const seenAll = new Set(Object.values(seen).flat());
const byName = new Map(allCustomers.map((c) => [c.name, c]));

/** 그 지역에 오는 손님: 그 지역 희귀손님 먼저, 그다음 지도 화면 순서대로 다른 손님 */
export const visitors = (r: string) => {
  const home = allCustomers.filter((c) => c.region === r);
  const list = seen[r]
    ? seen[r].map((n) => byName.get(n)!).filter((c) => c && c.region !== r)
    : allCustomers.filter((c) => c.region !== r && ((c as any).where ?? []).includes(r));
  const extra = seen[r] ? allCustomers.filter((c) => c.region !== r && !seenAll.has(c.name) && ((c as any).where ?? []).includes(r)) : [];
  return [...home, ...list, ...extra];
};
export const regionUrl = (r: string) => `${base}/regions/${regions.find((x) => x.name === r)?.slug}/`;
